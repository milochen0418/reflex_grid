"""Regenerates ``gridcore/engine/macro/constants_data.py``: the enumeration constants of Excel's and
Office's object libraries (``xlUp``, ``xlPasteValues``, ``msoTrue``…) and their enum type names
(``XlDirection``…), which VBA code uses without declaring them.

They are read from the type libraries that Microsoft Excel for Mac installs (only names and
numbers are taken, nothing else from those files):

    poetry run python scripts/gen_vba_constants_mac.py

The type library format (MSFT) is the one Wine's ``oleaut32/typelib.c`` reads.
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path
from typing import Dict, List, Tuple

LIBS = Path("/Applications/Microsoft Excel.app/Contents/SharedSupport/Type Libraries")
OUT = Path(__file__).resolve().parents[1] / "gridcore" / "engine" / "macro" / "constants_data.py"


def read_enums(path: Path) -> Dict[str, List[Tuple[str, int]]]:
    """{enum name: [(constant, value)…]} of an MSFT type library (enums and modules)."""
    data = path.read_bytes()

    def i32(o: int) -> int:
        return struct.unpack_from("<i", data, o)[0]

    if data[:4] != b"MSFT":
        raise ValueError(f"{path} isn't an MSFT type library")
    varflags, count = i32(0x14), i32(0x20)
    pos = 0x54 + (4 if varflags & 0x100 else 0) + 4 * count
    segments = [struct.unpack_from("<iiii", data, pos + 16 * k)[:2] for k in range(15)]
    typeinfos, names, custdata = segments[0][0], segments[7][0], segments[11][0]

    def name(offset: int) -> str:
        base = names + offset
        return data[base + 12: base + 12 + data[base + 8]].decode("latin-1")

    def value(offs: int) -> object:
        if offs < 0:  # small values are packed into the offset itself
            return offs & 0x3FFFFFF
        o = custdata + offs
        vt = struct.unpack_from("<H", data, o)[0]
        if vt in (3, 22):
            return i32(o + 2)
        if vt == 2:
            return struct.unpack_from("<h", data, o + 2)[0]
        if vt in (19, 23):
            return struct.unpack_from("<I", data, o + 2)[0]
        return None

    out: Dict[str, List[Tuple[str, int]]] = {}
    for i in range(count):
        b = typeinfos + i * 0x64
        kind = i32(b) & 0xF
        members = i32(b + 4)
        nfuncs, nvars = i32(b + 0x18) & 0xFFFF, (i32(b + 0x18) >> 16) & 0xFFFF
        if kind not in (0, 2) or nvars == 0:  # TKIND_ENUM, TKIND_MODULE
            continue
        size = i32(members)
        records, o = [], members + 4
        while o < members + 4 + size:
            n = i32(o) & 0xFFFF
            if n <= 0:
                break
            records.append(o)
            o += n
        arrays = members + 4 + size
        total = nfuncs + nvars
        consts = []
        for k, rec in enumerate(records[nfuncs: nfuncs + nvars]):
            if struct.unpack_from("<H", data, rec + 12)[0] != 2:  # VAR_CONST
                continue
            v = value(i32(rec + 16))
            if isinstance(v, int):
                consts.append((name(i32(arrays + 4 * (total + nfuncs + k))), v))
        if consts:
            out[name(i32(b + 0x34))] = consts
    return out


def main() -> int:
    if not LIBS.exists():
        print("This needs Microsoft Excel for Mac (its type libraries).")
        return 2
    excel = read_enums(LIBS / "Microsoft Excel.tlb")
    office = read_enums(LIBS / "mso.tlb")
    seen: Dict[str, int] = {}
    lines: List[str] = []
    # Excel's library comes before Office's in a project's references: its names win (a name
    # in several enums keeps its first value; each enum still lists all its members).
    for lib, enum_map, keep in (("Excel", excel, lambda n: not n.startswith("_")), ("Office", office, lambda n: n.startswith("mso"))):
        for enum, consts in enum_map.items():
            rows = [(n, v) for n, v in consts if keep(n)]
            if enum.startswith("_") or not rows:
                continue
            lines.append(f"# {lib}.{enum}")
            for n, v in rows:
                seen.setdefault(n.lower(), v)
                lines.append(f"{n} {v}")
    body = "\n".join(lines)
    OUT.write_text(
        '"""Enumeration constants of Excel\'s and Office\'s object libraries, by enum. Generated by\n'
        "scripts/gen_vba_constants_mac.py from the type libraries Excel for Mac installs; don't edit.\"\"\"\n\n"
        f'DATA = """\n{body}\n"""\n',
        "utf-8",
    )
    print(f"{OUT}: {len(seen)} constants, {sum(1 for x in lines if x.startswith('#'))} enums")
    return 0


if __name__ == "__main__":
    sys.exit(main())
